/** Lugares ocupados de ejemplo (solo para el modo demo). */
export const ocupacionDemo: Record<string, number> = {};

type HorarioEjemplo = [Dia, string, number];

function clase(datos: Omit<Clase, "horarios" | "activa" | "foto" | "orden"> & { cupo: number; horarios: HorarioEjemplo[] }, orden: number): Clase {
  const { cupo, horarios, ...resto } = datos;
  return {
    ...resto,
    activa: true,
    foto: null,
    orden,
    horarios: horarios.map(([dia, hora, libres]): Horario => {
      const id = `${datos.id}-${dia}-${hora.replace(":", "")}`;
      ocupacionDemo[id] = cupo - libres;
      return { id, claseId: datos.id, dia, hora, cupo, activo: true };
    }),
  };
}

